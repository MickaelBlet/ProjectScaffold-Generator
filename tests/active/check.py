"""Check of the active modules' queue (scripts/check_templates.sh): active_demo/active.py of
tests/fixtures/active.scaffold.yaml, generated by the python set. Prints "ok" or the failed checks.
Usage: python3 check.py <directory holding the active_demo package>"""
import sys
import threading
import time

sys.path.insert(0, sys.argv[1])

from active_demo.active import ActiveError, ActiveQueue  # noqa: E402

failures = 0


def expect(ok, what):
    global failures
    if not ok:
        print('FAILED:', what, file=sys.stderr)
        failures += 1


class Busy(Exception):
    pass


def main():
    q = ActiveQueue(8, 1000)
    ran = []
    expect(q.call(lambda: ran.append(threading.current_thread()) or 42) == 42, 'call returns the result')
    expect(ran[0] is not threading.current_thread(), 'call runs on the module thread')

    def busy():
        raise Busy('full')
    try:
        q.call(busy)
        expect(False, 'call raises the exception of the handler')
    except Busy:
        pass
    expect(q.call(lambda: q.call(lambda: 7)) == 7, 'a call from the module thread runs at once')
    q.close()

    order = []
    q = ActiveQueue(64, 1000)
    for i in range(20):
        q.post(lambda i=i: order.append(i))
    q.close()
    expect(order == list(range(20)), 'posted calls run in order, all of them')

    late = []
    q = ActiveQueue(8, 50)
    q.post(lambda: time.sleep(0.2))
    try:
        q.call(lambda: late.append(1))
        expect(False, 'call times out')
    except ActiveError:
        pass
    q.close()
    expect(not late, 'a call given up does not run')

    go = threading.Event()
    q = ActiveQueue(1, 1000, 'error')
    q.post(go.wait)
    time.sleep(0.02)
    q.post(lambda: None)
    try:
        q.post(lambda: None)
        expect(False, 'overflow error raises on a full queue')
    except ActiveError:
        pass
    go.set()
    q.close()

    count = []
    go = threading.Event()
    q = ActiveQueue(1, 1000, 'drop')
    q.post(go.wait)
    time.sleep(0.02)
    q.post(lambda: count.append(1))
    q.post(lambda: count.append(1))
    go.set()
    q.close()
    expect(len(count) == 1, 'overflow drop loses the call')

    if failures:
        sys.exit(1)
    print('ok')


main()
